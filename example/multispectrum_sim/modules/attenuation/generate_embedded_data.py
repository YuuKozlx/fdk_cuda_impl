#!/usr/bin/env python3
"""Generate the compiled-in MDATX3 database from the reference text files."""

from __future__ import annotations

import argparse
from pathlib import Path


def render(data_directory: Path) -> str:
    records: list[str] = []
    names: list[str] = []
    for atomic_number in range(1, 101):
        path = data_directory / f"MDATX3.{atomic_number:03d}"
        # Some historical tables end with the DOS 0x1a EOF marker. It is not
        # data and MSVC treats it as source-file EOF even inside a raw string.
        text = path.read_text(encoding="ascii").replace("\x1a", "")
        # Keep the generated header free of trailing whitespace while
        # preserving the MDATX3 token stream consumed by the parser.
        text = "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
        delimiter = f"XCOM{atomic_number:03d}"
        if f"){delimiter}\"" in text:
            raise ValueError(f"raw-string delimiter collision in {path}")
        name = f"kMdatx3_{atomic_number:03d}"
        names.append(name)
        records.append(
            f'static const char {name}[] = R"{delimiter}({text}){delimiter}";'
        )

    table = "\n".join(f"    {name}," for name in names)
    payload = "\n\n".join(records)
    return f"""// Generated by scripts/generate_embedded_data.py. Do not edit manually.
#pragma once

namespace nist_xcom_embedded {{

{payload}

static const char* const kMdatx3[100] = {{
{table}
}};

inline const char* find(int atomic_number) noexcept
{{
    return atomic_number >= 1 && atomic_number <= 100
        ? kMdatx3[atomic_number - 1]
        : nullptr;
}}

}} // namespace nist_xcom_embedded
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, default=Path("data"))
    parser.add_argument("--output", type=Path, default=Path("xcom_embedded_data.h"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    generated = render(args.data)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="ascii") != generated:
            raise SystemExit(f"{args.output} is not up to date")
        return
    args.output.write_text(generated, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
